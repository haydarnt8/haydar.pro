/**
 * Text set in a script font as one SVG path per letter, for the intro to draw. Run once; the output is committed.
 *   node scripts/generate-signature.mjs <font.ttf> [text] [family label] [out.ts] [preview.svg]
 * Use an OFL font: its outlines are embedded in the output.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import opentype from 'opentype.js'

const [, , fontPath, text = 'Haydar', family = 'unknown', outTs = 'app/assets/signature.ts', preview] = process.argv
if (!fontPath) { console.error('font path required'); process.exit(1) }

const buf = readFileSync(fontPath)
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
const SIZE = 300
const glyphPaths = font.getPaths(text, 0, 0, SIZE, { kerning: true })

let x1 = Infinity, y1 = Infinity, x2 = -Infinity, y2 = -Infinity
const letters = glyphPaths.map((p, i) => {
  const bb = p.getBoundingBox()
  x1 = Math.min(x1, bb.x1); y1 = Math.min(y1, bb.y1); x2 = Math.max(x2, bb.x2); y2 = Math.max(y2, bb.y2)
  return { index: i, char: text[i], d: p.toPathData(2) }
})
const pad = 10
const viewBox = `${(x1 - pad).toFixed(1)} ${(y1 - pad).toFixed(1)} ${(x2 - x1 + 2 * pad).toFixed(1)} ${(y2 - y1 + 2 * pad).toFixed(1)}`

const ts = `/* Generated by scripts/generate-signature.mjs — do not edit by hand.
   "${text}" set in ${family} (OFL), ${SIZE} units/em, one path per letter. */
export const signature = {
  text: ${JSON.stringify(text)},
  family: ${JSON.stringify(family)},
  viewBox: ${JSON.stringify(viewBox)},
  width: ${(x2 - x1 + 2 * pad).toFixed(1)},
  height: ${(y2 - y1 + 2 * pad).toFixed(1)},
  letters: [
${letters.map(l => `    { index: ${l.index}, char: ${JSON.stringify(l.char)}, d: ${JSON.stringify(l.d)} },`).join('\n')}
  ],
} as const
`
writeFileSync(outTs, ts)

if (preview) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="900" style="background:#1f1f1f">
${letters.map(l => `  <path d="${l.d}" fill="#f4f5f6" stroke="#f4f5f6" stroke-width="3" stroke-linejoin="round"/>`).join('\n')}
</svg>`
  writeFileSync(preview, svg)
}
console.log(`${family}: ${letters.length} letters, viewBox ${viewBox} -> ${outTs}${preview ? ' + ' + preview : ''}`)
