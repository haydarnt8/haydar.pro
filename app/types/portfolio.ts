export type Lang = 'en' | 'ar'

export interface Bilingual {
  en: string
  ar: string
}

/** One language for a name, both for prose. */
export type Text = string | Bilingual

/** `T` as authored in `app/data/`: any string may be bilingual. */
export type Authored<T> = T extends string
  ? Text
  : T extends (infer U)[]
    ? Authored<U>[]
    : T extends object
      ? { [K in keyof T]: Authored<T[K]> }
      : T

export function isBilingual(value: unknown): value is Bilingual {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return false
  const keys = Object.keys(value)
  return keys.length === 2 && typeof (value as Bilingual).en === 'string' && typeof (value as Bilingual).ar === 'string'
}

function resolve(value: unknown, lang: Lang): unknown {
  if (isBilingual(value)) return value[lang]
  if (Array.isArray(value)) return value.map(v => resolve(v, lang))
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, lang)]))
  }
  return value
}

export function localize<T>(value: Authored<T>, lang: Lang): T {
  return resolve(value, lang) as T
}

export const TODO_PREFIX = 'TODO:'

export function todo(what: string): string {
  return `${TODO_PREFIX} ${what}`
}

export function isTodo(value: unknown): boolean {
  return typeof value === 'string' && value.startsWith(TODO_PREFIX)
}

export const PLACEHOLDER_IMAGE = '/placeholder.png'

export function isPlaceholderImage(src: string | null): boolean {
  return src === PLACEHOLDER_IMAGE
}

